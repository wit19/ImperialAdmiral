        static readonly Dictionary<string, int> RowIndex = BuildIndex();

        static Dictionary<string, int> BuildIndex()
        {
            var ix = new Dictionary<string, int>(StringComparer.Ordinal);
            for (int i = 0; i < CrosswalkRows.Length; i++)
            {
                var r = CrosswalkRows[i];
                ix[RowKey(r.Expansion, r.TileId, r.Side)] = i;
            }
            return ix;
        }

        static string RowKey(string expansion, string tileId, string side)
        {
            return expansion + "|" + tileId + "|" + side;
        }

        public static bool TryRow(string expansion, string tileId, string side, out CrosswalkRow row)
        {
            int i;
            if (expansion == null || tileId == null)
            {
                row = null;
                return false;
            }
            if (RowIndex.TryGetValue(RowKey(expansion, tileId, NormalizeSide(side)), out i))
            {
                row = CrosswalkRows[i];
                return true;
            }
            row = null;
            return false;
        }

        // --------------------------------------------------- tile status ----
        /// <summary>D1/D2 tile-level law. Resolution order (the enumeration
        /// is the mother of all interior rules, Thomas 09.11): (1) RR core
        /// pins decide by (expansion, id) BEFORE any biome evidence - core
        /// 19..36 read Banned although their A-side label says "Imperial",
        /// core 38/39 read Open although they carry "None"; (2) the signed
        /// crosswalk row; (3) unsigned row or missing row -> Ambiguous
        /// (fail-OPEN at the consumer, never silently, D2).</summary>
        public static TileStatus StatusForTile(string expansion, string tileId,
                                               string side, string biome)
        {
            string reason;
            return StatusForTile(expansion, tileId, side, biome, out reason);
        }

        public static TileStatus StatusForTile(string expansion, string tileId,
                                               string side, string biome,
                                               out string reason)
        {
            int id = 0;
            bool numeric = tileId != null && int.TryParse(tileId, out id);
            if (numeric && (RrInterior(expansion, id) || RrExterior(expansion, id)))
            {
                // RR enumeration: physical tile property, the biome label is
                // NOT evidence against it (census section 2). A drifted biome
                // argument cannot un-pin an enumerated tile.
                reason = ReasonRrPin;
                return RrInterior(expansion, id) ? TileStatus.Banned : TileStatus.Open;
            }
            CrosswalkRow row;
            if (TryRow(expansion, tileId, side, out row))
                return StatusForRow(row, biome, out reason);
            reason = ReasonRowMissing;
            return TileStatus.Ambiguous;
        }

        /// <summary>The per-row reading law, exposed so the signature path is
        /// testable before any row is signed (and so a later hop can resolve
        /// a freshly signed row without re-keying the table).</summary>
        public static TileStatus StatusForRow(CrosswalkRow row, string placedBiome)
        {
            string reason;
            return StatusForRow(row, placedBiome, out reason);
        }

        public static TileStatus StatusForRow(CrosswalkRow row, string placedBiome,
                                              out string reason)
        {
            int id;
            bool numeric = int.TryParse(row.TileId, out id);
            // the enumeration is expansion-scoped: use the ROW's expansion,
            // never a hardcoded "Core" - a non-Core row must never inherit
            // the Core pin (spec section 7 numeric-overlap error class).
            if (row.RrEnumerated && numeric && (RrInterior(row.Expansion, id) || RrExterior(row.Expansion, id)))
            {
                reason = ReasonRrPin;
                return RrInterior(row.Expansion, id) ? TileStatus.Banned : TileStatus.Open;
            }
            if (row.Ruling == "")
            {
                // Unsigned candidate: evidence only, never law (D2).
                reason = ReasonRowUnsigned;
                return TileStatus.Ambiguous;
            }
            if (row.Ruling == "AMBIGUOUS")
            {
                reason = ReasonRowSigned;
                return TileStatus.Ambiguous;
            }
            if (placedBiome != row.Biome)
            {
                // Mapping verification stays fail-CLOSED (D2 "distinction"):
                // a signature covers the ROW it was given for, not a drifted
                // placement that merely shares the key.
                reason = ReasonBiomeDrift;
                return TileStatus.Ambiguous;
            }
            if (row.Ruling == "BANNED")
            {
                reason = ReasonRowSigned;
                return TileStatus.Banned;
            }
            if (row.Ruling == "OPEN")
            {
                reason = ReasonRowSigned;
                return TileStatus.Open;
            }
            reason = ReasonRulingInvalid;
            return TileStatus.Ambiguous;
        }

