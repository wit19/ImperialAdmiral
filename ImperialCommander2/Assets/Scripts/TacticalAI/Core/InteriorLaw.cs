        /// <summary>D1 four-state derivation over the tiles under one
        /// section. Mirror of the H1 census sec_state law (the data-side
        /// twin shipped in P41a), so census counts and the live rail cannot
        /// disagree about what MIXED means:
        ///   empty (no tile under the section)      -> Ambiguous (never silently OPEN)
        ///   Banned + Open present                  -> Mixed   (street-plus-room, the common case)
        ///   unresolved + anything resolved         -> Mixed   (the resolved half is fact, the
        ///                                                      unresolved half owes the forensic line)
        ///   nothing but unresolved                 -> Ambiguous (reads OPEN by D2 fail-open + log)
        ///   every tile Banned                      -> Banned  (pure-interior section: a real hole)
        ///   every tile Open                        -> Open    (full Massive use)
        /// A section is NOT an interior-property carrier (median 2 sections
        /// vs ~17 tiles per mission - 07.11 census): MIXED keeps the section
        /// traversable with the printed stay-out reminder (D1 self-
        /// correction), only pure-Banned sections are graph holes.</summary>
        public static SectionStatusT SectionStatus(IList<TileStatus> tilesUnderSection)
        {
            if (tilesUnderSection == null || tilesUnderSection.Count == 0)
                return SectionStatusT.Ambiguous;
            bool hasB = false, hasO = false, hasU = false;
            for (int i = 0; i < tilesUnderSection.Count; i++)
            {
                var t = tilesUnderSection[i];
                if (t == TileStatus.Banned) hasB = true;
                else if (t == TileStatus.Open) hasO = true;
                else hasU = true;
            }
            if (hasB && hasO) return SectionStatusT.Mixed;
            if (hasU && (hasB || hasO)) return SectionStatusT.Mixed;
            if (hasU) return SectionStatusT.Ambiguous;
            if (hasB) return SectionStatusT.Banned;
            return SectionStatusT.Open;
        }

        /// <summary>Forensic duty (D2 "never silently"): true iff the section
        /// reading involved an unresolved tile - the "[interior] ambigious-
        /// tile" line names exactly these sections (also the empty ones).</summary>
        public static bool SectionNeedsAmbiguousForensic(IList<TileStatus> tilesUnderSection)
        {
            if (tilesUnderSection == null || tilesUnderSection.Count == 0) return true;
            for (int i = 0; i < tilesUnderSection.Count; i++)
                if (tilesUnderSection[i] == TileStatus.Ambiguous) return true;
            return false;
        }

        // --------------------------------------------- graph view + seal ----
        /// <summary>Massive goal/distance view (D3-A): the not-Banned node
        /// filter over the derived section-status map. Open and Mixed pass
        /// (MIXED is legal ground with the stay-out reminder); Ambiguous
        /// passes FAIL-OPEN (D2) - the caller owes the forensic line; a
        /// section missing from the map passes like Ambiguous (unresolved,
        /// same duty). Only pure-Banned sections are holes - interior status
        /// is static public map data, so a hole is a fact, not belief.</summary>
        public static Func<string, bool> NotBanned(IDictionary<string, SectionStatusT> sectionStatus)
        {
            if (sectionStatus == null) return s => true;
            return s =>
            {
                SectionStatusT st;
                return !sectionStatus.TryGetValue(s, out st) || st != SectionStatusT.Banned;
            };
        }

        /// <summary>D3-A seal the approach: nearest OPEN section reachable
        /// from the Banned target over passable ground. Passable = anything
        /// not Banned (an Ambiguous section is fail-open traversable; the
        /// Massive can stand there, but it is NOT a seal target - the order
        /// holds verified open ground). The target itself never qualifies.
        /// Fixed tie law (spec 9.4): nearest BFS layer, then ordinal-
        /// smallest section id. Returns null when no open ground is
        /// reachable - the caller states the honest absence, never a chase.</summary>
        public static string SealSection(string bannedSection,
                                         Func<string, IEnumerable<string>> neighbours,
                                         Func<string, SectionStatusT> statusOf)
        {
            if (bannedSection == null || neighbours == null || statusOf == null) return null;
            var visited = new HashSet<string>(StringComparer.Ordinal) { bannedSection };
            var queue = new Queue<string>();
            var depth = new Dictionary<string, int>(StringComparer.Ordinal);
            queue.Enqueue(bannedSection);
            depth[bannedSection] = 0;
            string best = null;
            int bestDist = int.MaxValue;
            while (queue.Count > 0)
            {
                var cur = queue.Dequeue();
                int d = depth[cur];
                if (d >= bestDist) break;           // deeper layers cannot beat the seal
                var ns = neighbours(cur);
                if (ns == null) continue;
                var list = new List<string>();
                foreach (var n in ns)
                    if (n != null && !visited.Contains(n) && !list.Contains(n)) list.Add(n);
                list.Sort(StringComparer.Ordinal);   // deterministic BFS expansion
                foreach (var n in list)
                {
                    visited.Add(n);
                    var st = statusOf(n);
                    if (st == SectionStatusT.Open)
                    {
                        if (d + 1 < bestDist || (d + 1 == bestDist &&
                            string.CompareOrdinal(n, best) < 0))
                        {
                            best = n;
                            bestDist = d + 1;
                        }
                        continue;                    // an Open reached through an Open is strictly farther - never a closer seal, never routed through
                    }
                    if (st == SectionStatusT.Banned)
                        continue;                    // holes are never routes
                    depth[n] = d + 1;
                    queue.Enqueue(n);
                }
            }
            return best;
        }

        // -------------------------- P41d: anchor mask + ingress fact --------
        // (CONCEPT_massive_interior_v1.md v1.3 9.3-2/9.3-3, 4-D3-A, 5-H4.)
        // Two PURE decisions - the same functions the live bridge seams
        // call (anchor mask at the HeroInSection read sites; REPLAN fact 4
        // at the MIDROUND-REPLAN block). Harness: massive_interior.json
        // vectors "anchor" + "replan" (SectionsInterior.cs) - mirror-of-one,
        // no second implementation.

        /// <summary>Result of one anchor-mask decision: the section the
        /// consumer must actually use plus the fact that drives its
        /// disclosure line. NEVER null - pass-through always echoes the
        /// input.</summary>
        public sealed class AnchorMaskResult
        {
            public string Section;    // anchor to hand to the consumer ("" = honest absence: no anchor at all)
            public string Fact;       // one of the Mask* constants below
            public string Original;   // the anchor as read (forensic line input)
        }

        public const string MaskNone = "";
        public const string MaskSeal = "seal";                    // 9.3-2: Banned anchor replaced by SealSection
        public const string MaskSealMissing = "seal_missing";     // Banned, no open ground reachable: NO anchor, never a chase
        public const string MaskAdvisory = "advisory";            // Mixed goal: stays allowed, order carries the printed stay-out reminder (4-D3-A)
        public const string MaskAmbiguous = "ambiguous";          // D2 fail-open; the caller owes the forensic line

        /// <summary>9.3-2 goal masking at an anchor read: when the anchor
        /// section is Banned for THIS card (Massive, no D6 override), the
        /// consumer gets the seal-the-approach section instead of the hole
        /// (nearest open neighbour, 4-D3-A) - and with SealSection's null
        /// answer it gets NO anchor at all: the honest absence, never a
        /// chase into the hole. MIXED is legal ground (D1): the goal stays,
        /// the fact says advisory (the printed stay-out reminder rides the
        /// order). AMBIGUOUS passes fail-open (D2) with its fact for the
        /// forensic line. Non-Massive cards and D6-covered cards return the
        /// input untouched - their line stays bit-identical (mode/massive/
        /// override gates live here so every read site reads one law).</summary>
        public static AnchorMaskResult AnchorMaskFor(string anchorSection,
                                                     bool isMassive, bool overrideCovers,
                                                     Func<string, IEnumerable<string>> neighbours,
                                                     Func<string, SectionStatusT> statusOf)
        {
            var r = new AnchorMaskResult
            {
                Section = anchorSection ?? "",
                Fact = MaskNone,
                Original = anchorSection ?? "",
            };
            if (string.IsNullOrEmpty(anchorSection)) return r;   // Null-Law: no anchor, no claim
            if (neighbours == null || statusOf == null) return r; // no graph/no map: no claim, untouched
            if (!isMassive || overrideCovers) return r;           // today's line, bit-identical
            var st = statusOf(anchorSection);
            if (st == SectionStatusT.Open) return r;              // legal ground: bit-identical
            if (st == SectionStatusT.Mixed) { r.Fact = MaskAdvisory; return r; }
            if (st == SectionStatusT.Ambiguous) { r.Fact = MaskAmbiguous; return r; }
            // Banned (the only hole): the consumer never sees it.
            var seal = SealSection(anchorSection, neighbours, statusOf);
            r.Section = seal ?? "";
            r.Fact = seal != null ? MaskSeal : MaskSealMissing;
            return r;
        }

        /// <summary>9.3-3 REPLAN fact 4 (InteriorIngress): a tracked anchor
        /// hero whose CURRENT section is Banned and DIFFERENT from the
        /// section the plan was built against flipped into a hole mid-round
        /// - the same-round rebuild trigger. Returns the hero key of the
        /// first hit in CALLER order (the caller's order is deterministic;
        /// the fact carries no ranking of its own). Null = fact silent:
        /// no anchor moved into a hole. An anchor that already sat in the
        /// same Banned section at build time is NOT a flip - that plan was
        /// built masked (no trigger loop, the rebuild re-captures).</summary>
        public static string IngressFact(
            IEnumerable<KeyValuePair<string, string>> anchorAtBuild,
            Func<string, string> currentSectionOf,
            Func<string, SectionStatusT> statusOf)
        {
            if (anchorAtBuild == null || currentSectionOf == null || statusOf == null) return null;
            foreach (var kv in anchorAtBuild)
            {
                if (string.IsNullOrEmpty(kv.Key)) continue;
                var cur = currentSectionOf(kv.Key);
                if (string.IsNullOrEmpty(cur)) continue;   // no observed fact, no claim (Null-Law)
                if (string.Equals(cur, kv.Value, StringComparison.Ordinal)) continue;  // no switch, no ingress
                if (statusOf(cur) == SectionStatusT.Banned) return kv.Key;
            }
            return null;
        }

