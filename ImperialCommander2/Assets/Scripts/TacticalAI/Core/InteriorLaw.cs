        // RR enumeration (the printed law, Core expansion only):
        //   19A-36A and 19B-36B interior (banned); 38A/38B/39A/39B exterior.
        public const int RrInteriorFirst = 19;
        public const int RrInteriorLast = 36;
        public const int RrExteriorFirst = 38;
        public const int RrExteriorLast = 39;

        /// <summary>True iff (Core expansion) id+side is RR-enumerated
        /// interior (banned). Keyed (expansion, id) - expansion ids never
        /// join the enumeration (census section 10).</summary>
        public static bool RrInterior(string expansion, int tileId)
        {
            return expansion == "Core" && tileId >= RrInteriorFirst && tileId <= RrInteriorLast;
        }

        public static bool RrExterior(string expansion, int tileId)
        {
            return expansion == "Core" && tileId >= RrExteriorFirst && tileId <= RrExteriorLast;
        }

        /// <summary>GetBiomeType law (MapTile.cs): tileSide=="A" reads side A,
        /// anything else reads B; the census coerces missing to A.</summary>
        public static string NormalizeSide(string side)
        {
            return (side == null || side.Length == 0 || side == "A") ? "A" : "B";
        }

