            public List<string> CardNames()
            {
                var l = new List<string>(_cards);
                l.Sort(StringComparer.Ordinal);
                return l;
            }

            /// <summary>D6 registration law, fail-closed (v1.3 finding 4).
            /// authoredDpStatus is the StatusForTile read of the authored
            /// DP's own tile:
            ///   Banned    -> VERIFIED-BANNED (RR pin or signed row only -
            ///                 an unsigned row can never BE Banned here) ->
            ///                 register: OverrideRegistered.
            ///   Ambiguous -> candidate-BANNED / unresolved mapping: registers
            ///                 NOTHING, the caller logs override_unverified +
            ///                 the ban STAYS until the table is fixed.
            ///   Open      -> outdoor placement, nothing to lift.
            /// Re-registration of the same card is idempotent (set
            /// semantics - the shipped pointList repeats the DP per figure,
            /// and a multi-event respawn of the same card adds no new
            /// state). Returns the fact for the [interior]/massive-override
            /// forensic line.</summary>
            public string RegisterAuthored(string cardName, TileStatus authoredDpStatus)
            {
                if (cardName == null) return OverrideUnverified;
                if (authoredDpStatus == TileStatus.Banned)
                {
                    _cards.Add(cardName);
                    return OverrideRegistered;
                }
                return authoredDpStatus == TileStatus.Open
                    ? OverrideOutdoorNoneed
                    : OverrideUnverified;
            }
        }
