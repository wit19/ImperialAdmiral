    /// <summary>One crosswalk row (census schema wa.massive_crosswalk/1):
    /// (expansion, tileID, side) + the shipped per-side biome label, the
    /// UNSIGNED census candidate reading (evidence, never law), the RR
    /// enumeration flag and the Thomas signature slot. Rows are data.</summary>
    public sealed class CrosswalkRow
    {
        public readonly string Expansion;   // dimensions.json expansion name
        public readonly string TileId;      // decimal id string
        public readonly string Side;        // "A"/"B", normalized by the GetBiomeType law
        public readonly string Biome;       // per-side BiomeType label as shipped
        public readonly string Candidate;   // H1 census reading ("BANNED_CANDIDATE" = unsigned interior evidence)
        public readonly bool RrEnumerated;  // row named by the RR core enumeration
        public readonly string Ruling;      // Thomas signature; "" = unsigned

        public CrosswalkRow(string expansion, string tileId, string side,
                            string biome, string candidate, bool rrEnumerated, string ruling)
        {
            Expansion = expansion;
            TileId = tileId;
            Side = side;
            Biome = biome;
            Candidate = candidate;
            RrEnumerated = rrEnumerated;
            Ruling = ruling ?? "";
        }
    }

