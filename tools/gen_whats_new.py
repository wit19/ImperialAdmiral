#!/usr/bin/env python3
"""Generate the "What's new" block at the top of docs/WIKI_tactical_ai.md.

The player wiki is append-only: dated `## Section (Month ...)` chapters are
appended at the bottom over the months, so "what changed lately" forces
scrolling through 2000+ lines. This tool maintains a SHORT generated digest
between the two marker lines right after the first horizontal rule.

Laws of this tool (P44 docs hop, 21.11.):
- Pure insertion. The chapter body is NEVER touched; without the markers the
  tool inserts exactly one block after the first `---` line; with markers it
  replaces only what sits between them. Re-running changes nothing (idempotent).
- The chapters themselves are the source: the tool adds no information of its
  own. A new dated chapter + one `gen_whats_new.py` run = fresh digest.
- `--check` (gate mode): regenerate in memory and exit 1 on drift, print the
  diff. This is what QA runs, so the digest can never silently age.
- The version line reads TacticalAiBuildStamp.Value — the same truth the
  title badge tells (P35 lockstep), never a second hand-typed version.
"""
import re
import sys
import difflib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DOC = REPO / "docs" / "WIKI_tactical_ai.md"
STAMP = REPO / "ImperialCommander2" / "Assets" / "Scripts" / "TacticalAI" / "TacticalAiBuildStamp.cs"
BEGIN = "<!-- WHATSNEW:BEGIN (generated by tools/gen_whats_new.py - do not edit inside) -->"
END = "<!-- WHATSNEW:END -->"
MAX_ENTRIES = 8

def version():
    m = re.search(r'Value\s*=\s*"([^"]+)"', STAMP.read_text(encoding="utf-8"))
    return m.group(1) if m else "unknown"

def slug(title):
    # GitHub's anchor law: lowercase, drop punctuation (keep - and spaces),
    # spaces -> hyphens.
    s = title.lower()
    s = re.sub(r"[^\w\s-]", "", s, flags=re.UNICODE)
    return re.sub(r"\s+", "-", s.strip())

def sections(text):
    """[(title, date)] of dated `## ` chapters, in DOCUMENT order (append
    order == chronological, per the docs law)."""
    out = []
    for m in re.finditer(r"^## (.+)$", text, flags=re.M):
        title = m.group(1).strip()
        dm = re.search(r"\(([^()]*(?:January|February|March|April|May|June|July|"
                       r"August|September|October|November|December|jan|feb|mar|"
                       r"apr|mai|jun|jul|aug|sep|okt|nov|dez|\d{4}-\d{2})[^()]*)\)\s*$",
                       title)
        if dm:
            date = dm.group(1).strip()
            bare = title[: dm.start()].strip().rstrip(",")
            out.append((bare, date, title))
    return out

def block_body(text):
    secs = sections(text)
    lines = [BEGIN]
    if secs:
        newest = secs[-1]
        lines.append(f"> **Stand:** {version()} — zuletzt: **{newest[0]}** ({newest[1]}).")
        lines.append(">")
        lines.append("> **Neu im Wiki** — neueste zuerst, Details in den Kapiteln:")
        for bare, date, full in reversed(secs[-MAX_ENTRIES:]):
            lines.append(f"> - **{date}** — [{bare}](#{slug(full)})")
        if len(secs) > MAX_ENTRIES:
            n = len(secs) - MAX_ENTRIES
            lines.append(f"> - ältere Gesetze: {n} "
                         + ("weiteres datiertes" if n == 1 else "weitere datierte")
                         + (" Kapitel" if n == 1 else " Kapitel") + " unterhalb.")
    else:
        lines.append(f"> **Stand:** {version()}")
    lines.append(END)
    return "\n".join(lines)

def render(text):
    """Return the document with the marker block placed/refreshed."""
    body = block_body(text)
    if BEGIN in text and END in text:
        pre, rest = text.split(BEGIN, 1)
        _, post = rest.split(END, 1)
        return pre + body + post
    lines = text.split("\n")
    try:
        i = lines.index("---")
    except ValueError:
        raise SystemExit("no first --- found; refusing to guess an insertion point")
    return "\n".join(lines[: i + 1]) + "\n\n" + body + "\n" + "\n".join(lines[i + 1:])

def main():
    check = "--check" in sys.argv
    text = DOC.read_text(encoding="utf-8")
    # the check compares AGAINST the chapter list computed from the file
    # with any previous block excluded (the block itself contains no ## lines)
    want = render(text)
    if want == text:
        print("whats_new: UP TO DATE" if check else "whats_new: no change needed")
        return 0
    if check:
        d = "\n".join(difflib.unified_diff(
            text.splitlines(), want.splitlines(),
            fromfile="wiki (as committed)", tofile="wiki (regenerated)", lineterm=""))
        print("whats_new: DRIFT — run tools/gen_whats_new.py and commit:\n" + d)
        return 1
    DOC.write_text(want, encoding="utf-8")
    print(f"whats_new: block refreshed ({section_count(want)} dated chapters listed "
          f"from, max {MAX_ENTRIES} shown)")

def section_count(t):
    return len(re.findall(r"^## ", t, flags=re.M))

if __name__ == "__main__":
    sys.exit(main())
